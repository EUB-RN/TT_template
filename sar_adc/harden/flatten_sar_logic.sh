#!/bin/bash
# Turn the ADC team's sar_logic gate netlist into generic logic so it can be
# re-synthesised together with sar_adc_axil, and prove the result equivalent.
# Nothing about the logic changes; only the cell mapping is thrown away.
#   $1        sar_logic_gate_level.v (inside sar_adc/tt_submission.rar)
#   PDK_ROOT  ciel/volare root that holds sky130A
#   YOSYS     yosys binary (default: yosys on PATH)
set -e
HERE=$(cd "$(dirname "$0")" && pwd)
IN=${1:?usage: flatten_sar_logic.sh sar_logic_gate_level.v}
: "${PDK_ROOT:?set PDK_ROOT to the directory that holds sky130A}"
Y=${YOSYS:-yosys}
LIB="$PDK_ROOT/sky130A/libs.ref/sky130_fd_sc_hd/lib/sky130_fd_sc_hd__tt_025C_1v80.lib"
OUT="$HERE/../rtl/sar_logic_flat.v"
TMP=$(mktemp -d)

# drop tap / decap / fill instances, they carry no logic
awk '
  /^ *sky130_fd_sc_hd__(decap|fill|tapvpwrvgnd)/ {skip=1}
  skip { if ($0 ~ /\);/) skip=0; next }
  {print}
' "$IN" > "$TMP/gl.v"

"$Y" -q -p "
  read_liberty -ignore_miss_func $LIB
  read_verilog $TMP/gl.v
  hierarchy -top sar_logic
  flatten
  opt_clean -purge
  techmap
  opt -full -purge
  rename -enumerate -pattern n%
  write_verilog -noattr $TMP/flat.v
"

{
  echo "// Generated by sar_adc/harden/flatten_sar_logic.sh from the ADC team's"
  echo "// sar_logic_gate_level.v: same logic, cell mapping removed. Do not edit."
  echo
  cat "$TMP/flat.v"
} > "$OUT"

# equivalence: original cells (liberty functions) vs the generic version
sed 's/^module sar_logic(/module sar_logic_flat(/' "$TMP/flat.v" > "$TMP/flat_renamed.v"
"$Y" -q -p "
  read_liberty -ignore_miss_func $LIB
  read_verilog $TMP/gl.v
  read_verilog $TMP/flat_renamed.v
  proc
  flatten
  opt_clean
  async2sync
  equiv_make sar_logic sar_logic_flat equiv
  hierarchy -top equiv
  equiv_simple -seq 5
  equiv_induct -seq 5
  tee -o $TMP/equiv.txt equiv_status -assert
"
grep -E 'Found|unproven|proven' "$TMP/equiv.txt" | head -3
echo "wrote $OUT"
